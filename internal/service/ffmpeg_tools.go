// Package service — FFmpeg/FFprobe 检测与下载安装。
// 检测、安装只返回候选路径；用户保存设置后才切换使用。
package service

import (
	"context"
	"errors"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"sync"
	"time"

	"go.uber.org/zap"

	"github.com/Ferrymania/nook/internal/config"
	"github.com/Ferrymania/nook/internal/helper"
)

type FFmpegToolsService struct {
	cfg          *config.Config
	log          *zap.Logger
	installTools func(context.Context, *zap.Logger, *config.Config, func(string)) (string, string, error)
	mu           sync.Mutex
	running      bool
	msg          string
	errMsg       string
	started      time.Time
	done         time.Time
}

func NewFFmpegToolsService(cfg *config.Config, log *zap.Logger) *FFmpegToolsService {
	return &FFmpegToolsService{cfg: cfg, log: log, installTools: installFFmpegTools}
}

func (s *FFmpegToolsService) ffmpegInstallDir() string {
	path := filepath.Join(s.cfg.App.DataDir, "tools", "ffmpeg")
	if absolute, err := filepath.Abs(path); err == nil {
		return absolute
	}
	return path
}

type ffToolInfo struct {
	Installed bool   `json:"installed"`
	Path      string `json:"path,omitempty"`
	Version   string `json:"version,omitempty"`
}

func inspectFFTool(ctx context.Context, path, name string) ffToolInfo {
	if path == "" {
		return ffToolInfo{}
	}
	ctx, cancel := context.WithTimeout(ctx, 3*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, path, "-version").Output() // #nosec G204 -- path is resolved locally or generated by the installer; no shell is used.
	if err != nil {
		return ffToolInfo{Path: path}
	}
	version := strings.TrimSpace(strings.SplitN(strings.TrimSpace(string(out)), "\n", 2)[0])
	return ffToolInfo{Installed: strings.HasPrefix(strings.ToLower(version), name+" version "), Path: path, Version: version}
}

// downloadedTools 兼容旧目录，并复用下载目录中已验证的完整工具。
func (s *FFmpegToolsService) downloadedTools(ctx context.Context) map[string]ffToolInfo {
	dirs := []string{s.ffmpegInstallDir()}
	entries, _ := os.ReadDir(s.ffmpegInstallDir())
	sort.Slice(entries, func(i, j int) bool { return entries[i].Name() > entries[j].Name() })
	for _, entry := range entries {
		if entry.IsDir() && strings.HasPrefix(entry.Name(), "download-") {
			dirs = append(dirs, filepath.Join(s.ffmpegInstallDir(), entry.Name()))
		}
	}
	exe := ""
	if runtime.GOOS == "windows" {
		exe = ".exe"
	}
	for _, dir := range dirs {
		if ctx.Err() != nil {
			break
		}
		ffmpeg := inspectFFTool(ctx, filepath.Join(dir, "ffmpeg"+exe), "ffmpeg")
		ffprobe := inspectFFTool(ctx, filepath.Join(dir, "ffprobe"+exe), "ffprobe")
		if ffmpeg.Installed && ffprobe.Installed {
			return map[string]ffToolInfo{"ffmpeg": ffmpeg, "ffprobe": ffprobe}
		}
	}
	return map[string]ffToolInfo{"ffmpeg": {}, "ffprobe": {}}
}

// Detect 查找可运行的程序，不修改数据库或运行时配置。
func (s *FFmpegToolsService) Detect(ctx context.Context) map[string]ffToolInfo {
	config.RuntimeMu.RLock()
	configured := map[string]string{"ffmpeg": s.cfg.App.FFmpegPath, "ffprobe": s.cfg.App.FFprobePath}
	config.RuntimeMu.RUnlock()
	found := map[string]ffToolInfo{"ffmpeg": {}, "ffprobe": {}}
	for _, name := range []string{"ffmpeg", "ffprobe"} {
		for _, path := range executableCandidates(configured[name], name) {
			if ctx.Err() != nil {
				return found
			}
			if info := inspectFFTool(ctx, path, name); info.Installed {
				found[name] = info
				break
			}
		}
	}
	if !found["ffmpeg"].Installed || !found["ffprobe"].Installed {
		for name, info := range s.downloadedTools(ctx) {
			if !found[name].Installed {
				found[name] = info
			}
		}
	}
	return found
}

// Status 分开报告已生效配置和已下载工具，下载完成不代表配置已切换。
func (s *FFmpegToolsService) Status(ctx context.Context) map[string]any {
	s.mu.Lock()
	running, msg, errMsg, started, done := s.running, s.msg, s.errMsg, s.started, s.done
	s.mu.Unlock()
	startedAt, doneAt := "", ""
	if !started.IsZero() {
		startedAt = started.Format(time.RFC3339Nano)
	}
	if !done.IsZero() {
		doneAt = done.Format(time.RFC3339Nano)
	}
	out := map[string]any{
		"installing": running, "message": msg, "error": errMsg,
		"started_at": startedAt, "finished_at": doneAt, "install_dir": s.ffmpegInstallDir(),
	}
	target, err := ffmpegTargetForPlatform()
	if err != nil {
		out["target"] = map[string]any{"label": err.Error()}
	} else {
		out["target"] = map[string]any{"os": runtime.GOOS, "arch": runtime.GOARCH, "label": target.Label}
	}
	config.RuntimeMu.RLock()
	ffmpegPath, _ := resolveLocalExecutable(s.cfg.App.FFmpegPath, "ffmpeg")
	ffprobePath, _ := resolveLocalExecutable(s.cfg.App.FFprobePath, "ffprobe")
	config.RuntimeMu.RUnlock()
	out["ffmpeg"] = inspectFFTool(ctx, ffmpegPath, "ffmpeg")
	out["ffprobe"] = inspectFFTool(ctx, ffprobePath, "ffprobe")
	if !running {
		out["downloaded"] = s.downloadedTools(ctx)
	}
	return out
}

// StartInstall 复用完整工具；否则后台下载。两种情况都不会应用配置。
func (s *FFmpegToolsService) StartInstall(ctx context.Context) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	s.mu.Lock()
	if s.running {
		s.mu.Unlock()
		return errors.New("工具正在安装中，请稍候")
	}
	s.running, s.errMsg = true, ""
	s.started, s.done = time.Now(), time.Time{}
	s.mu.Unlock()
	ready := s.downloadedTools(ctx)
	if ready["ffmpeg"].Installed && ready["ffprobe"].Installed {
		s.mu.Lock()
		s.running, s.done = false, time.Now()
		s.msg = "工具已安装，路径可填入；点击保存后生效"
		s.mu.Unlock()
		return nil
	}
	s.setMessage("准备下载…")
	helper.Go(s.log, "ffmpeg.install", s.runInstall)
	return nil
}

// runInstall 只下载、解压和验证，不写数据库或运行时路径。
func (s *FFmpegToolsService) runInstall() {
	defer func() {
		s.mu.Lock()
		s.running, s.done = false, time.Now()
		s.mu.Unlock()
	}()
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Minute)
	defer cancel()
	ffmpeg, ffprobe, err := s.installTools(ctx, s.log, s.cfg, s.setMessage)
	if err != nil {
		s.mu.Lock()
		s.errMsg, s.msg = err.Error(), "安装失败"
		s.mu.Unlock()
		s.log.Error("ffmpeg 工具安装失败", zap.Error(err))
		return
	}
	s.setMessage("安装完成，尚未启用；点击保存后生效")
	s.log.Info("ffmpeg 工具安装完成，等待保存配置", zap.String("ffmpeg", ffmpeg), zap.String("ffprobe", ffprobe))
}

func (s *FFmpegToolsService) setMessage(msg string) {
	s.mu.Lock()
	s.msg = msg
	s.mu.Unlock()
}
